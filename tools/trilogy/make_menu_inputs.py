#!/usr/bin/env python3
"""Writes the QA input script that walks the Trilogy menu to Metroid Prime 3 (tools/trilogy/probe_title.ps1 -Script).

The menu only updates its hover from a pointer that moves, so each target is approached with a
short glide. Frames count from the first front-end frame. Order on screen: strap, intro, title,
Game Select (slot), Main Menu, Single Player Games, Select Difficulty.
"""
from pathlib import Path

A = 0x800
PARK = (0.9, 0.9)


def screen(x: int, y: int) -> tuple[float, float]:
    """Pointer position of a pixel in the 854x480 window: the game scales pointer X by 1.28 in 16:9."""
    return (x - 427) / 427 / 1.28, (y - 240) / 240


SLOT_1 = screen(235, 160)
START_SINGLE_PLAYER = screen(200, 165)
MP3_GAME_START = screen(200, 325)
DIFFICULTY_NORMAL = screen(200, 170)


def line(frame: int, hold: int, at: tuple[float, float]) -> str:
    return f"f {frame} h {hold:#x} s 0,0 p 1,{at[0]:.4f},{at[1]:.4f},1,0 r 0,0,0 n 0,0 g 0,0,0,0,0,0"


def glide(out: list[str], frame: int, start: tuple[float, float], end: tuple[float, float], frames: int = 40) -> int:
    for step in range(1, frames + 1):
        t = step / frames
        out.append(line(frame + step, 0, (start[0] + (end[0] - start[0]) * t, start[1] + (end[1] - start[1]) * t)))
    return frame + frames


def press(out: list[str], frame: int, at: tuple[float, float]) -> int:
    out.append(line(frame, A, at))
    out.append(line(frame + 6, 0, at))
    return frame + 6


def main() -> None:
    out = ["# prime-input-recording v1",
           "# Generated by make_menu_inputs.py: strap screen, intro, start, slot 1, single player, Metroid Prime 3, difficulty.",
           line(0, 0, PARK)]
    # Loads vary between runs, so every step has a wide margin.
    for frame in (400, 800, 1200):
        press(out, frame, PARK)
    previous = PARK
    for frame, target in ((1700, SLOT_1), (2300, START_SINGLE_PLAYER), (2900, MP3_GAME_START), (3500, DIFFICULTY_NORMAL)):
        end = glide(out, frame, previous, target)
        press(out, end + 20, target)
        previous = target
    out.append("end 12000")
    path = Path(__file__).with_name("menu_to_mp3.inputs.txt")
    path.write_text("\n".join(out) + "\n", encoding="ascii")
    print(path)


if __name__ == "__main__":
    main()
